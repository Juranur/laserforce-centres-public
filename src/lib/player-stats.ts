/**
 * Player-stats data layer.
 *
 * Source of truth: data/player-stats-history.json — committed by
 * scripts/fetch-player-stats.mjs on every update cycle (see
 * .github/workflows/update-player-stats.yml). Importing it statically means
 * each Vercel deploy (triggered by the workflow push) serves fresh data.
 *
 * The cumulative curve per player has two series:
 *  - "archive": one {t, missions} point per update cycle — grows forever
 *  - "exact":   per-mission totals from the API's last-30-missions window;
 *               after the i-th mission (oldest-first) of the last N, the
 *               career total was exactly totalMissions - (N-1-i)
 */
import historyJson from "../../data/player-stats-history.json";

export interface LeaderboardRow {
  rank: number;
  centre: string;
  codename: string;
  metric: number; // ranking value: games played (qt=0) or centres/arenas played (qt=1)
  avatar: string;
  token: string;
}

export interface GameTypeSummary {
  type: string;
  missions: number;
  lastPlayed: string | null; // "YYYY-MM-DD HH:MM:SS" — most recent mission of this type at this centre
}

export interface CentreEntry {
  name: string;
  missions: number;
  skillLevelNum: number;
  skillLevelName: string;
  joined: string;
  summary?: GameTypeSummary[]; // per-game-type breakdown with last-played dates (populated once the fetcher runs with summary capture)
}

export interface GameTypeEntry {
  type: string;
  missions: number;
}

export interface ArchivePoint {
  t: string; // ISO timestamp of the update cycle
  missions: number;
}

export interface RecentMission {
  date: string; // "YYYY-MM-DD HH:MM:SS" (site-local time)
  site: string;
  type: string;
  score: number;
}

export interface PlayerHistory {
  token: string;
  codename: string;
  avatar: string;
  joinDate: string | null;
  totalMissions: number;
  centres: CentreEntry[];
  gameTypes: GameTypeEntry[];
  archivePoints: ArchivePoint[];
  recentMissions: RecentMission[];
  lastFetched: string | null;
}

export interface PlayerStatsHistory {
  version: number;
  generated: string;
  cycle: number;
  note: string;
  leaderboards: {
    games: { queryType: number; centreId: number; rows: LeaderboardRow[] };
    arenas: { queryType: number; centreId: number; rows: LeaderboardRow[] };
    kiel: { queryType: number; centreId: number; rows: LeaderboardRow[] };
  };
  players: Record<string, PlayerHistory>;
}

const history = historyJson as unknown as PlayerStatsHistory;

export function getHistory(): PlayerStatsHistory {
  return history;
}

export function getPlayer(token: string): PlayerHistory | undefined {
  return history.players[token];
}

export function getTrackedPlayers(): PlayerHistory[] {
  // Stamp the storage key onto each player as `.token`. The history file is
  // generated by the fetch script, and entries written by older script versions
  // have no `token` property on the object (the key was correct, the field was
  // absent). The /players list builds its links from `p.token`, so deriving it
  // from the key here guarantees every link resolves via getPlayer — regardless
  // of history-file age.
  return Object.entries(history.players)
    .map(([token, p]) => ({ ...p, token }))
    .sort((a, b) => b.totalMissions - a.totalMissions);
}

/** "YYYY-MM-DD HH:MM:SS" (or ISO) -> epoch ms. Treated as UTC for charting. */
export function parseStamp(s: string): number {
  const iso = s.includes("T") ? s : s.replace(" ", "T") + "Z";
  return Date.parse(iso);
}

export interface SeriesPoint {
  t: number;
  missions: number;
  mission?: RecentMission;
}

export interface BuiltSeries {
  exact: SeriesPoint[];
  archive: SeriesPoint[];
  yDomain: [number, number];
}

export function buildSeries(player: PlayerHistory): BuiltSeries {
  const T = player.totalMissions || 0;

  const exact: SeriesPoint[] = [...(player.recentMissions ?? [])]
    .sort((a, b) => a.date.localeCompare(b.date))
    .map((m, i, arr) => ({
      t: parseStamp(m.date),
      missions: T - (arr.length - 1 - i),
      mission: m,
    }))
    .filter(p => Number.isFinite(p.t));

  const archive: SeriesPoint[] = (player.archivePoints ?? [])
    .map(a => ({ t: parseStamp(a.t), missions: a.missions }))
    .filter(p => Number.isFinite(p.t))
    .sort((a, b) => a.t - b.t);

  const values = [...exact, ...archive].map(p => p.missions);
  let min = values.length ? Math.min(...values) : 0;
  let max = values.length ? Math.max(...values) : 1;
  if (min === max) { min -= 2; max += 2; }
  const pad = Math.max(2, (max - min) * 0.12);

  return { exact, archive, yDomain: [min - pad, max + pad] };
}

export interface MergedPoint {
  t: number;
  exact: number | null;
  archive: number | null;
  estimate: number | null; // dashed pre-archive estimate: 0 at earliest join date → first real point
  mission?: RecentMission;
}

/** Merge both series onto one time axis (nulls break nothing with connectNulls). */
export function mergeSeries(series: BuiltSeries): MergedPoint[] {
  const map = new Map<number, MergedPoint>();
  for (const p of series.exact) {
    map.set(p.t, { t: p.t, exact: p.missions, archive: null, estimate: null, mission: p.mission });
  }
  for (const p of series.archive) {
    const existing = map.get(p.t);
    if (existing) existing.archive = p.missions;
    else map.set(p.t, { t: p.t, exact: null, archive: p.missions, estimate: null });
  }
  return [...map.values()].sort((a, b) => a.t - b.t);
}

/** A single (centre × game-type) linear ramp contributing to the cumulative estimate. */
interface EstimateSegment {
  startT: number; // centre join date (midnight UTC)
  endT: number;   // that game type's last-played date (or fallback window end)
  count: number;  // missions of this type at this centre (summary total)
}

/**
 * Collect the per-(centre × game-type) ramp segments that anchor the
 * pre-archive cumulative estimate. Each summary entry ramps from the centre's
 * join date to that game type's last-played date, reaching its mission count.
 * Entries without a lastPlayed (or centres whose summary has not been captured
 * yet) fall back to a ramp over [joined, fallbackEndT]. Degenerate spans
 * (end ≤ start) are spread over the fallback window so no segment collapses to
 * a vertical step.
 */
function collectEstimateSegments(player: PlayerHistory, fallbackEndT: number): EstimateSegment[] {
  const segs: EstimateSegment[] = [];
  for (const c of player.centres) {
    const startT = Date.parse((c.joined ?? "") + "T00:00:00Z");
    if (!Number.isFinite(startT)) continue;
    if (c.summary && c.summary.length) {
      for (const s of c.summary) {
        let endT = s.lastPlayed ? parseStamp(s.lastPlayed) : fallbackEndT;
        if (!Number.isFinite(endT) || endT <= startT) endT = fallbackEndT;
        if (endT <= startT) endT = startT + 1; // ultimate guard against div-by-zero
        segs.push({ startT, endT, count: s.missions });
      }
    } else if (c.missions > 0) {
      // no summary captured yet: ramp the centre's whole total over the window
      segs.push({ startT, endT: Math.max(fallbackEndT, startT + 1), count: c.missions });
    }
  }
  return segs;
}

/** Cumulative mission estimate at time T: sum of every segment's linear ramp. */
function estimateAt(segs: EstimateSegment[], T: number): number {
  let sum = 0;
  for (const s of segs) {
    if (T <= s.startT) continue;
    if (T >= s.endT) sum += s.count;
    else sum += (s.count * (T - s.startT)) / (s.endT - s.startT);
  }
  return sum;
}

/**
 * Build a piecewise-linear cumulative estimate over [joinT, firstRealT] from
 * the per-centre summary anchors: join dates, per-game-type last-played dates,
 * and per-segment mission counts. Each (centre × game type) contributes a
 * linear ramp; summed, the curve ramps up as centres come online and plateaus
 * as centres go dormant — far more shape-accurate than a single straight line,
 * and anchored by real measured dates and totals (only the within-segment rate
 * is assumed uniform). Calibrated so the estimate meets firstVal at firstRealT,
 * handing off cleanly to the real archive/exact curve. Returns sorted knot
 * points including both endpoints.
 */
export function buildEstimateKnots(
  player: PlayerHistory,
  joinT: number,
  firstRealT: number,
  firstVal: number,
): { t: number; estimate: number }[] {
  if (joinT >= firstRealT) return [];
  const segs = collectEstimateSegments(player, firstRealT);
  if (!segs.length) {
    return [{ t: joinT, estimate: 0 }, { t: firstRealT, estimate: firstVal }];
  }

  // knot times where the slope can change: the two endpoints plus every
  // segment start/end that falls strictly inside the window
  const knotSet = new Set<number>([joinT, firstRealT]);
  for (const s of segs) {
    if (s.startT > joinT && s.startT < firstRealT) knotSet.add(s.startT);
    if (s.endT > joinT && s.endT < firstRealT) knotSet.add(s.endT);
  }
  const knots = [...knotSet].sort((a, b) => a - b);

  const rawAtEnd = estimateAt(segs, firstRealT);
  const scale = rawAtEnd > 0 ? firstVal / rawAtEnd : 1;

  const out = knots.map(t => ({
    t,
    estimate: Math.max(0, Math.round(estimateAt(segs, t) * scale)),
  }));
  // pin the endpoints exactly: start at 0, meet the real first data point
  out[0] = { t: joinT, estimate: 0 };
  out[out.length - 1] = { t: firstRealT, estimate: firstVal };
  return out;
}

/**
 * Inject the pre-archive "estimated history" segment from the player's earliest
 * centre-join date to the first real data point.
 *
 * The Laserforce API exposes no per-mission history before the last-30 window
 * and no past career totals, so the span between "joined" and "first archive
 * point" cannot be measured directly. Instead of a single straight line, this
 * builds a piecewise-linear estimate from the per-centre summary anchors (join
 * dates, per-game-type last-played dates, per-segment mission counts): each
 * (centre × game type) ramps linearly over its active span, so the curve ramps
 * up as centres come online and plateaus as they go dormant. Endpoints and
 * totals are real measured data; only the within-segment rate is assumed
 * uniform. Knot points carry `estimate` only (exact/archive null); the chart's
 * estimate Line renders them as a dashed polyline via its contiguous non-null
 * run.
 */
export function withEstimate(merged: MergedPoint[], player: PlayerHistory): MergedPoint[] {
  if (!merged.length) return merged;

  const joinTs = player.centres
    .map(c => Date.parse((c.joined ?? "") + "T00:00:00Z"))
    .filter(t => Number.isFinite(t));
  if (!joinTs.length) return merged;

  const joinT = Math.min(...joinTs);
  const first = merged[0];
  // only add an estimate when the join date actually predates the real data
  if (joinT >= first.t) return merged;

  const firstVal = first.exact ?? first.archive ?? 0;
  const knots = buildEstimateKnots(player, joinT, first.t, firstVal);
  // drop the final knot (at first.t) — the first real point carries the
  // estimate there, so the dashed estimate Line hands off to the real curve.
  const interior: MergedPoint[] = knots.slice(0, -1).map(k => ({
    t: k.t, exact: null, archive: null, estimate: k.estimate,
  }));
  const tagged = merged.map((p, i) =>
    i === 0 ? { ...p, estimate: firstVal } : { ...p, estimate: null },
  );
  return [...interior, ...tagged].sort((a, b) => a.t - b.t);
}

